/**
 * Generate docs/conformance/manifest-consumption-level-1.md (MC-1) from
 * UNVERIFIED_OBLIGATION_CONSUMER_CONTRACT and MIGRATION.md (SDD §3, FR-C4).
 *
 * The whole document is rendered here so the contract table cannot drift
 * from the code: tests/constraints/manifest-consumption-doc.test.ts renders
 * it again and compares byte-for-byte. The v9.0.0 flip statement is copied
 * verbatim from MIGRATION.md's "Planned v9.0.0 fail-closed default flip"
 * subsection, so editing that subsection also requires regenerating.
 *
 * Usage:
 *   tsx scripts/generate-manifest-contract-doc.ts          # write
 *   tsx scripts/generate-manifest-contract-doc.ts --check  # exit 1 on drift
 *
 * @since v8.8.0
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  FAIL_CLOSED_DEFAULT_FLIP_VERSION,
  UNVERIFIED_OBLIGATION_CONSUMER_CONTRACT,
  UNVERIFIED_OBLIGATION_REASONS,
} from '../src/constraints/unverified-obligations.js';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const MC1_DOC_PATH = join(REPO_ROOT, 'docs', 'conformance', 'manifest-consumption-level-1.md');
const MIGRATION_PATH = join(REPO_ROOT, 'MIGRATION.md');
const FLIP_HEADING = '### Planned v9.0.0 fail-closed default flip';

/** Extract the body of MIGRATION.md's flip subsection (heading excluded). */
export function extractFlipStatement(migration: string): string {
  const start = migration.indexOf(FLIP_HEADING);
  if (start < 0) throw new Error(`MIGRATION.md: missing "${FLIP_HEADING}" subsection`);
  const rest = migration.slice(start + FLIP_HEADING.length);
  const end = rest.search(/\n(?:#{1,3} |---\n)/);
  return (end < 0 ? rest : rest.slice(0, end)).trim();
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

export function renderManifestContractDoc(migration: string): string {
  const rows = UNVERIFIED_OBLIGATION_REASONS.map((reason) => {
    const r = UNVERIFIED_OBLIGATION_CONSUMER_CONTRACT[reason];
    return `| \`${reason}\` | ${r.level} | ${cell(r.action)} | ${cell(r.judgement_requested)} | ${r.affected_by_fail_closed_flip ? 'yes' : 'no'} |`;
  });
  return `<!-- GENERATED by scripts/generate-manifest-contract-doc.ts. Do not edit by hand; run \`npx tsx scripts/generate-manifest-contract-doc.ts\`. -->

# Manifest Consumption, Level 1 (MC-1)

**Since:** v8.8.0 (SDD §3, FR-C4).

\`validate()\` returns an \`unverified_obligations\` manifest whenever the
library skipped a check that the consumer must perform. Examples are a
signature it did not verify, a hash it did not recompute, or a delegation
chain it was not given. MC-1 is the minimum a consumer does with that
manifest to claim it consumed it.

The library ships the shape of the obligation and the question to ask. The
consumer, and the human approvers it designates, supply the answer
(ADR-010).

## What an MC-1 consumer MUST do

1. **Read the manifest.** Treat absence of \`unverified_obligations\` as "no
   obligations". Treat presence as "the record is not yet authoritative".
2. **Apply the contract row for each entry.** For every entry in
   \`unverified_rules\` that carries a \`reason\`, look up the row below; the
   entry itself carries the row's \`judgement_requested\` and
   \`consumer_obligation_level\`. Perform the row's action. A consumer MAY
   act more strictly than the row; it MUST NOT act more weakly. Entries
   without a \`reason\` are discharged from their \`evaluation_note\`.
3. **Record a receipt.** Produce one \`ManifestConsumptionReceipt\` per
   manifest, with exactly one decision per manifest \`rule_id\`. Each
   decision carries the approver's \`judgement\`, which answers the row's
   question. The receipt is identified with its manifest by \`schema_id\`,
   \`contract_version\` and \`manifest_emitted_at\`.
4. **Check completeness.** Every manifest \`rule_id\` has a decision, and no
   decision names a rule the manifest does not carry (MCR-3).
   \`joinReceiptToManifest(manifest, receipt).complete\` performs this join.
5. **Fail closed on \`rejected\`.** If any decision is \`rejected\`, do not
   act on the record. Treat \`escalated\` the same way until the escalation
   resolves. \`joinReceiptToManifest(...).mc1_satisfied\` is \`false\` in
   both cases.

\`mc1_satisfied: true\` means only that the receipt meets MC-1. It is not an
authorization decision; the consumer's own policy still applies.

## What the library does not do

- It does not grade judgements (MCR-N1). Any non-empty judgement of at most
  1024 characters is structurally valid.
- It does not decide who may approve. \`decided_by\` and \`consumer_id\` are
  opaque.
- It does not sign receipts. Wrap a receipt in a \`SignatureEnvelope\` when
  non-repudiation is needed.

## Consumer-obligation contract

Rendered from \`UNVERIFIED_OBLIGATION_CONSUMER_CONTRACT\`. The last column
is \`affected_by_fail_closed_flip\`: whether the planned v${FAIL_CLOSED_DEFAULT_FLIP_VERSION} default flip changes
the \`validate()\` outcome for records carrying that reason.

| Reason | Level | Action | Judgement requested | Changes at v${FAIL_CLOSED_DEFAULT_FLIP_VERSION} |
|--------|-------|--------|---------------------|----------------|
${rows.join('\n')}

## Planned v${FAIL_CLOSED_DEFAULT_FLIP_VERSION} fail-closed default flip

Copied verbatim from MIGRATION.md:

${extractFlipStatement(migration)}
`;
}

const isMain = process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const expected = renderManifestContractDoc(readFileSync(MIGRATION_PATH, 'utf8'));
  if (process.argv.includes('--check')) {
    let actual = '';
    try {
      actual = readFileSync(MC1_DOC_PATH, 'utf8');
    } catch {
      // fall through to drift
    }
    if (actual !== expected) {
      console.error('DRIFT: docs/conformance/manifest-consumption-level-1.md is stale; run npx tsx scripts/generate-manifest-contract-doc.ts');
      process.exit(1);
    }
    console.log('OK: MC-1 doc matches the consumer-obligation contract');
  } else {
    mkdirSync(dirname(MC1_DOC_PATH), { recursive: true });
    writeFileSync(MC1_DOC_PATH, expected);
    console.log(`Wrote ${MC1_DOC_PATH}`);
  }
}
